from io import BytesIO
from xml.sax.saxutils import escape

from reportlab.lib import colors
from reportlab.lib.enums import TA_CENTER
from reportlab.lib.pagesizes import A4
from reportlab.lib.styles import getSampleStyleSheet, ParagraphStyle
from reportlab.lib.units import inch
from reportlab.platypus import (
    SimpleDocTemplate,
    Paragraph,
    Spacer,
    Table,
    TableStyle
)


def generate_career_pdf(profile, career, roadmap, questions):

    buffer = BytesIO()

    document = SimpleDocTemplate(
        buffer,
        pagesize=A4,
        rightMargin=45,
        leftMargin=45,
        topMargin=45,
        bottomMargin=45
    )

    styles = getSampleStyleSheet()

    title_style = ParagraphStyle(
        "CareerTitle",
        parent=styles["Title"],
        alignment=TA_CENTER,
        textColor=colors.darkblue
    )

    story = []

    story.append(
        Paragraph("CAREERCRAFT AI", title_style)
    )

    story.append(
        Paragraph("Personalized Career Development Report",
                  styles["Heading2"])
    )

    story.append(Spacer(1, 15))

    story.append(Paragraph("Student Profile", styles["Heading1"]))

    for key in ["name", "email", "branch", "career_goal"]:
        value = escape(str(profile.get(key, "Not provided")))
        story.append(
            Paragraph(f"<b>{key.replace('_', ' ').title()}:</b> {value}",
                      styles["Normal"])
        )

    story.append(Spacer(1, 15))

    story.append(Paragraph("Career Analysis", styles["Heading1"]))

    story.append(
        Paragraph(
            f"<b>Recommended Career:</b> {escape(str(career.get('career', 'Not available')))}",
            styles["Normal"]
        )
    )

    story.append(
        Paragraph(
            f"<b>Skill Match:</b> {career.get('match_percentage', 0)}%",
            styles["Normal"]
        )
    )

    story.append(Spacer(1, 10))

    story.append(Paragraph("Matched Skills", styles["Heading2"]))

    matched = career.get("matched_skills", [])
    story.append(
        Paragraph(
            escape(", ".join(matched) if matched else "No matched skills"),
            styles["Normal"]
        )
    )

    story.append(Paragraph("Skills to Improve", styles["Heading2"]))

    missing = career.get("missing_skills", [])
    story.append(
        Paragraph(
            escape(", ".join(missing) if missing else "No missing skills"),
            styles["Normal"]
        )
    )

    story.append(Spacer(1, 15))

    story.append(Paragraph("Learning Roadmap", styles["Heading1"]))

    for item in roadmap:
        story.append(
            Paragraph(
                f"<b>Week {item['week']}: {escape(str(item['skill']))}</b>",
                styles["Normal"]
            )
        )

        for task in item["tasks"]:
            story.append(
                Paragraph(f"- {escape(str(task))}", styles["Normal"])
            )

        story.append(Spacer(1, 8))

    story.append(Paragraph("Interview Preparation", styles["Heading1"]))

    for index, question in enumerate(questions, start=1):
        story.append(
            Paragraph(
                f"<b>Q{index}. {escape(str(question['question']))}</b>",
                styles["Normal"]
            )
        )

        story.append(
            Paragraph(
                f"Answer: {escape(str(question['answer']))}",
                styles["Normal"]
            )
        )

        story.append(Spacer(1, 8))

    story.append(Spacer(1, 20))

    story.append(
        Paragraph(
            "Generated by CareerCraft AI. "
            "This report provides educational guidance and does not "
            "guarantee employment or career outcomes.",
            styles["Italic"]
        )
    )

    document.build(story)

    buffer.seek(0)

    return buffer.getvalue()